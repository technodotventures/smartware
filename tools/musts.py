"""Build spec/MUSTS.md: every MUST/REQUIRED sentence in the spec, with its id, level and covering tests."""
from __future__ import annotations

import ast
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEVEL = {}
for ids, lvl in (("02 03 04 05 06 07 08 09 12 13 14 15 16 17 18 21 22 23 24 25 26 37 38 39 40 41 43 44 50 51 53 56", "L1"),
                 ("10 11 20 34 35 36 48 49 52", "L2"),
                 ("32 33 45 54 55 57 58 59 60 61", "L3"),
                 ("19 27 28 29 30 31 42 46 47 62", "L4")):
    for i in ids.split():
        LEVEL[f"M{i}"] = lvl
META = {"M65"}
RETIRED = {"M01": "described the document, not engines", "M63": "folded into M65", "M64": "folded into M65"}
LEVEL.update({"M66": "L3", "M67": "L3", "M68": "L2", "M69": "L3", "M70": "L1", "M71": "L4", "M72": "L3",
              "M73": "L3", "M74": "L3", "M75": "L2", "M76": "L2", "M77": "L3"})
NA = {"M57": "no connectors ship with the reference engine"}


def musts():
    """MUSTs carry stable ids in the spec text as `[Mnn]`. Sentences with MUST/REQUIRED but no id are reported."""
    s = open(os.path.join(ROOT, "spec", "Smartware-0.1.md")).read()
    sec, out, missing = "0", [], []
    for line in s.split("\n"):
        m = re.match(r"^#{2,3} (\d+(\.\d+)?|Appendix \w)", line)
        if m:
            sec = m.group(1)
        if "RFC 2119" in line:
            continue
        for sent in re.split(r"(?<=[.;\]])\s+(?=[A-Z`(])", line):
            if re.search(r"\bMUST\b|\bREQUIRED\b", sent):
                ids = re.findall(r"\[(M\d{2})\]", sent)
                text = re.sub(r"\s*\[M\d{2}\]", "", sent).strip().lstrip("-| ").strip()
                if not ids:
                    missing.append(text[:80])
                for i in ids:
                    out.append((i, sec, text))
    if missing:
        print("MUST sentences without an id:", missing)
    return sorted(out)


def tests():
    cov = {}
    for f in glob.glob(os.path.join(ROOT, "tests", "**", "test_*.py"), recursive=True):
        tree = ast.parse(open(f).read())
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                for tok in node.name.split("_")[1:]:
                    m = re.fullmatch(r"M(\d{2})[a-z]?", tok)
                    if not m:
                        break
                    cov.setdefault(f"M{m.group(1)}", []).append(f"{os.path.relpath(f, ROOT)}::{node.name}")
    return cov


def main():
    cov = tests()
    rows = ["# Smartware 0.1 MUST checklist", "",
            "Generated by `tools/musts.py` from `spec/Smartware-0.1.md` and the test names in `tests/`. "
            "Ids are stable `[Mnn]` tags in the spec text and are never reused. Retired: " +
            ", ".join(f"{k} ({v})" for k, v in sorted(RETIRED.items())) + ".", "",
            "| Id | § | Level | Requirement | Tests |", "|---|---|---|---|---|"]
    untested = []
    for mid, sec, text in musts():
        t = cov.get(mid, [])
        lvl = "meta" if mid in META else LEVEL.get(mid, "?")
        if mid in NA:
            cell = f"n/a: {NA[mid]}"
        elif mid in META:
            cell = "process requirement"
        elif t:
            cell = "<br>".join(f"`{x.split('::')[1]}`" for x in t)
        else:
            cell = "**untested**"
            untested.append(mid)
        rows.append(f"| {mid} | {sec} | {lvl} | {text.replace('|', '/')[:220]} | {cell} |")
    rows += ["", f"Untested: {', '.join(untested) if untested else 'none'}."]
    open(os.path.join(ROOT, "spec", "MUSTS.md"), "w").write("\n".join(rows) + "\n")
    n = len({mid for mid, _, _ in musts()})
    print(f"{n} MUST ids, untested: {untested}")


if __name__ == "__main__":
    main()
